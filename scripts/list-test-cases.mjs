#!/usr/bin/env node
// Builds docs/TEST_CASES.md from the test names in the code.
//   node scripts/list-test-cases.mjs          rewrite the file
//   node scripts/list-test-cases.mjs --check  fail if the file is out of date
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, basename } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const out = join(root, "docs/TEST_CASES.md");
const rel = (p) => relative(root, p).split("\\").join("/");

function walk(dir, match, acc = []) {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name.startsWith(".")) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, match, acc);
    else if (match(p)) acc.push(p);
  }
  return acc.sort();
}

const sentence = (s) => s.charAt(0).toUpperCase() + s.slice(1);
// A describe() named after a function stays as code: `pageList`.
const areaName = (s) => (/^[A-Za-z_$][\w$]*$/.test(s) && /[a-z][A-Z]/.test(s) ? `\`${s}\`` : sentence(s));
const cell = (s) => s.replace(/\|/g, "\\|");

// describe/it/test names in a TypeScript test file, in order.
function jsCases(file) {
  const src = readFileSync(file, "utf8");
  const re = /\b(describe|it|test)(?:\.(?:each\([^)]*\)|skipIf\([^)]*\)|only|skip))?\(\s*(["'`])((?:\\.|(?!\2)[\s\S])*?)\2/g;
  const cases = [];
  let area = "";
  for (const m of src.matchAll(re)) {
    const name = m[3].replace(/\\(.)/g, "$1").replace(/\s+/g, " ").trim();
    if (m[1] === "describe") area = name;
    else cases.push({ area, name });
  }
  return cases;
}

// #[test] functions in the contract tests.
function rustCases(file) {
  const src = readFileSync(file, "utf8");
  return [...src.matchAll(/#\[test\](?:\s*#\[[^\]]*\])*\s*fn\s+([a-z0-9_]+)/g)].map((m) => ({ name: m[1].replace(/_/g, " ") }));
}

const unitFiles = walk(join(root, "app/src"), (p) => p.endsWith(".test.ts") && !p.endsWith(".integration.test.ts"));
const suites = [
  {
    id: "UNIT", title: "Unit tests", tool: "Vitest", run: "cd app && npm test",
    cases: unitFiles.flatMap((f) => jsCases(f).map((c) => ({ ...c, file: f }))),
  },
  {
    id: "CON", title: "Contract tests", tool: "Rust", run: "cargo test",
    cases: rustCases(join(root, "contracts/signing/src/test.rs")).map((c) => ({ ...c, file: join(root, "contracts/signing/src/test.rs") })),
  },
  {
    id: "E2E", title: "End-to-end tests", tool: "Playwright", run: "cd app && npm run test:e2e",
    cases: jsCases(join(root, "app/e2e/signing.spec.ts")).map((c) => ({ ...c, file: join(root, "app/e2e/signing.spec.ts") })),
  },
  {
    id: "TNET", title: "Testnet integration", tool: "Vitest, Stellar testnet", run: "cd app && INTEGRATION=1 npx vitest run src/lib/stellar/testnet.integration.test.ts",
    cases: jsCases(join(root, "app/src/lib/stellar/testnet.integration.test.ts")).map((c) => ({ ...c, file: join(root, "app/src/lib/stellar/testnet.integration.test.ts") })),
  },
];

const total = suites.reduce((n, s) => n + s.cases.length, 0);
const lines = [
  "# Test cases",
  "",
  "<!-- Generated by scripts/list-test-cases.mjs. Don't edit by hand: run `node scripts/list-test-cases.mjs`. -->",
  "",
  `Every automated test in Signcerely, **${total} in total**. IDs follow the order of the tests in the code.`,
  "",
  "| Suite | Tool | Cases | Run it with |",
  "|---|---|---|---|",
  ...suites.map((s) => `| [${s.title}](#${s.title.toLowerCase().replace(/ /g, "-")}) | ${s.tool} | ${s.cases.length} | \`${s.run}\` |`),
  "",
];
for (const s of suites) {
  const pad = String(s.cases.length).length < 2 ? 2 : String(s.cases.length).length;
  const showArea = s.cases.some((c) => c.area);
  lines.push(`## ${s.title}`, "");
  lines.push(showArea ? "| ID | Area | Test case | File |" : "| ID | Test case | File |");
  lines.push(showArea ? "|---|---|---|---|" : "|---|---|---|");
  s.cases.forEach((c, i) => {
    const id = `${s.id}-${String(i + 1).padStart(pad, "0")}`;
    const file = `[${basename(c.file)}](../${rel(c.file)})`;
    lines.push(showArea
      ? `| ${id} | ${cell(areaName(c.area || ""))} | ${cell(sentence(c.name))} | ${file} |`
      : `| ${id} | ${cell(sentence(c.name))} | ${file} |`);
  });
  lines.push("");
}
const text = lines.join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8"); } catch {}
  if (current !== text) {
    console.error("docs/TEST_CASES.md is out of date. Run: node scripts/list-test-cases.mjs");
    process.exit(1);
  }
  console.log(`docs/TEST_CASES.md is up to date (${total} test cases).`);
} else {
  writeFileSync(out, text);
  console.log(`Wrote docs/TEST_CASES.md (${total} test cases).`);
}
